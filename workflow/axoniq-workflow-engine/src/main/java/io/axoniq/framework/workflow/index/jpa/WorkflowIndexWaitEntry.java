package io.axoniq.framework.workflow.index.jpa;

import jakarta.persistence.Basic;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.Id;
import jakarta.persistence.Index;
import jakarta.persistence.Table;
import org.axonframework.common.IdentifierFactory;
import org.jspecify.annotations.Nullable;

import java.util.Objects;

/**
 * The row of one open wait in the {@link JpaWorkflowIndex}: which workflow waits, in which step, for which event.
 *
 * @author Stefan Dragisic
 * @see io.axoniq.framework.workflow.runtime.execution.WaitAssociation
 * @since 5.5.0
 */
@Entity
@Table(indexes = {
        @Index(columnList = "workflowModule,segmentKey"),
        @Index(columnList = "workflowModule,workflowId")
})
public class WorkflowIndexWaitEntry {

    // Assigned here, not generated by the database, so the JdbcWorkflowIndex writes the same table.
    @Id
    @Column(length = 255)
    private String id;

    @Basic(optional = false)
    @Column(length = 255)
    private String workflowModule;

    @Basic(optional = false)
    @Column(length = 255)
    private String workflowId;

    @Basic(optional = false)
    @Column(length = 1024)
    private String stepName;

    @Basic(optional = false)
    private long segmentKey;

    private @Nullable String eventName;

    // Not a large object: a claim reads every wait of its segment, and a large object costs a round trip per row.
    @Basic
    @Column(length = 10000)
    private byte[] associations;

    /**
     * Constructor required by JPA. Do not use.
     */
    protected WorkflowIndexWaitEntry() {
    }

    /**
     * Creates the row of an open wait.
     *
     * @param workflowModule the name of the workflow module the workflow runs in
     * @param workflowId     the identifier of the waiting workflow
     * @param stepName       the name of the wait step
     * @param segmentKey     the segment key of the workflow id
     * @param eventName      the name of the awaited event, or {@code null} when the wait accepts any event
     * @param associations   the converted associations the awaited event must match
     */
    public WorkflowIndexWaitEntry(String workflowModule,
                                String workflowId,
                                String stepName,
                                long segmentKey,
                                @Nullable String eventName,
                                byte[] associations) {
        this.id = IdentifierFactory.getInstance().generateIdentifier();
        this.workflowModule = Objects.requireNonNull(workflowModule, "The workflow module must not be null.");
        this.workflowId = Objects.requireNonNull(workflowId, "The workflow id must not be null.");
        this.stepName = Objects.requireNonNull(stepName, "The step name must not be null.");
        this.segmentKey = segmentKey;
        this.eventName = eventName;
        this.associations = Objects.requireNonNull(associations, "The associations must not be null.");
    }

    /**
     * Returns the identifier of the waiting workflow.
     *
     * @return the identifier of the workflow
     */
    public String getWorkflowId() {
        return workflowId;
    }

    /**
     * Returns the name of the wait step.
     *
     * @return the name of the wait step
     */
    public String getStepName() {
        return stepName;
    }

    /**
     * Returns the name of the awaited event.
     *
     * @return the name of the awaited event, or {@code null} when the wait accepts any event
     */
    public @Nullable String getEventName() {
        return eventName;
    }

    /**
     * Returns the converted associations the awaited event must match.
     *
     * @return the converted associations
     */
    public byte[] getAssociations() {
        return associations;
    }
}
