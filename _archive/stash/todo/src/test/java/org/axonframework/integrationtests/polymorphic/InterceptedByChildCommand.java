package org.axonframework.integrationtests.polymorphic;

import org.axonframework.modelling.command.TargetAggregateIdentifier;

/**
 * The command intercepted by the one of children's command handler interceptor and handled by parent aggregate.
 *
 * @author Milan Savic
 */
public class InterceptedByChildCommand {

    @TargetAggregateIdentifier
    private final String id;
    private String state;

    public InterceptedByChildCommand(String id, String state) {
        this.id = id;
        this.state = state;
    }

    public String getId() {
        return id;
    }

    public String getState() {
        return state;
    }

    public void setState(String state) {
        this.state = state;
    }
}
